#!/usr/bin/env bash
# Script auxiliar para orientar download de modelos locais (não baixa pesos automaticamente).
# Uso: ajustar variáveis abaixo e seguir instruções do modelo escolhido.

# Exemplo: GPT4All local
# DUQUE_LOCAL_BACKEND=gpt4all
# DUQUE_LOCAL_MODEL_PATH=/caminho/para/gpt4all-model.bin

# Exemplo: llama-cpp
# DUQUE_LOCAL_BACKEND=llama
# DUQUE_LOCAL_MODEL_PATH=/caminho/para/ggml-model.bin

cat <<'EOF'
Este script é um placeholder. Modelos locais não serão baixados automaticamente por razões de tamanho/licença.
Siga as instruções do provedor do modelo (gpt4all, llama.cpp, etc.) para baixar pesos e definir DUQUE_LOCAL_MODEL_PATH.
EOF

exit 0
